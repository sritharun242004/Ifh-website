import type { Metadata, Viewport } from "next";
import { Hanken_Grotesk, Manrope, Montserrat, Noto_Sans_Tamil } from "next/font/google";
import { MetaPixel } from "@/landing/components/MetaPixel";
import { copy } from "@/landing/copy";
import "./landing.css";

/* Owner landing page root layout. Separate from (site) so none of the legacy CSS/JS ships here.
   Only the headline font is preloaded. */
const manrope = Manrope({
  subsets: ["latin"],
  weight: ["800"],
  variable: "--f-head",
  display: "swap",
});
const hanken = Hanken_Grotesk({
  subsets: ["latin"],
  weight: ["400", "500", "600"],
  variable: "--f-body",
  display: "swap",
  preload: false,
});
const montserrat = Montserrat({
  // latin-ext carries the ₹ glyph; it is only downloaded when ₹ is on screen (unicode-range).
  subsets: ["latin", "latin-ext"],
  weight: ["800", "900"],
  variable: "--f-num",
  display: "swap",
  preload: false,
});
const tamil = Noto_Sans_Tamil({
  subsets: ["tamil"],
  weight: ["800"],
  variable: "--f-ta",
  display: "swap",
  preload: false,
});

export const metadata: Metadata = {
  title: copy.meta.title,
  description: copy.meta.description,
  // www is the host that actually serves the app (the apex does not), so the
  // generated OG image + canonical resolve to a URL crawlers can fetch.
  metadataBase: new URL("https://www.ifindhouse.in"),
  applicationName: "IFH",
  alternates: { canonical: "/" },
  keywords: [
    "rent house no broker",
    "zero commission rentals",
    "post house free",
    "Tamil Nadu rentals",
    "IFH",
    "I Find House",
  ],
  icons: { icon: "/assets/logo.svg", apple: "/assets/logo.png" },
  // The OG + Twitter image is generated by app/(landing)/opengraph-image.tsx,
  // so it always matches the live campaign copy.
  openGraph: {
    type: "website",
    siteName: "IFH",
    title: copy.meta.title,
    description: copy.meta.description,
    url: "https://www.ifindhouse.in/",
    locale: "en_IN",
  },
  twitter: {
    card: "summary_large_image",
    title: copy.meta.title,
    description: copy.meta.description,
  },
  robots: {
    index: true,
    follow: true,
    googleBot: { index: true, follow: true, "max-image-preview": "large" },
  },
};

export const viewport: Viewport = {
  themeColor: "#ffffff",
  width: "device-width",
  initialScale: 1,
  viewportFit: "cover",
};

export default function LandingRootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html
      lang="en-IN"
      className={`${manrope.variable} ${hanken.variable} ${montserrat.variable} ${tamil.variable}`}
    >
      <body>
        {/* A refresh always starts at the top: no restored scroll position, no jump to an old #anchor.
            Runs before the page content parses. */}
        <script
          dangerouslySetInnerHTML={{
            __html: `(function(){try{if("scrollRestoration" in history)history.scrollRestoration="manual";if(location.hash){history.replaceState(null,"",location.pathname+location.search);addEventListener("DOMContentLoaded",function(){scrollTo({top:0,left:0,behavior:"instant"})})}}catch(e){}})();`,
          }}
        />
        {children}
        <MetaPixel />
      </body>
    </html>
  );
}
